"""Phase-0 deterministic builders for the new landing-page flow.

Writes everything that doesn't need an LLM:
  • src/app/globals.css      — Tailwind directives + palette HSL CSS vars
  • src/app/layout.jsx       — root layout with Google Fonts from Brief
  • src/lib/design-system.js — minimal motion/container/section_padding tokens
  • src/components/ui/Reveal.jsx — scroll-triggered entrance wrapper

Header + footer are NOT written here anymore — they are generated by
landing_section_codegen.generate_layout_components() based on the Brief's
header_archetype + footer_archetype. We do still write deterministic STUB
fallbacks so layout.jsx imports never fail if codegen errored.
"""
from __future__ import annotations

import logging
import os
from typing import Any

logger = logging.getLogger(__name__)


# ── globals.css ──────────────────────────────────────────────────────

_GLOBALS_TEMPLATE = """@tailwind base;
@tailwind components;
@tailwind utilities;

@layer base {{
  :root {{
{palette_vars}
    --radius: 0.625rem;
  }}

  * {{
    @apply border-border;
  }}

  html {{
    scroll-behavior: smooth;
  }}

  body {{
    @apply bg-background text-foreground;
    font-family: var(--font-body, "{body_font}"), system-ui, -apple-system, sans-serif;
  }}

  h1, h2, h3, h4, h5, h6 {{
    font-family: var(--font-heading, "{heading_font}"), system-ui, sans-serif;
  }}

  /* Anchor jumps must clear sticky/fixed headers */
  section[id], div[id] {{
    scroll-margin-top: 5rem;
  }}

  /* Horizontal overflow is contained by the body wrapper so sticky
     elements (the marketing header) keep working. Setting overflow-x
     on html or body silently breaks `position: sticky`. */
  body {{
    overflow-x: clip;
  }}
}}
"""


def _palette_vars(palette: dict[str, str]) -> str:
    keys = ["background", "foreground", "primary", "secondary", "accent",
            "muted", "border", "card"]
    lines = []
    for k in keys:
        v = (palette.get(k) or "").strip()
        if not v:
            continue
        lines.append(f"    --{k}: {v};")
        if k == "background":
            lines.append(f"    --foreground-on-bg: {palette.get('foreground', '0 0% 10%')};")
    # Derived foregrounds for shadcn semantic pairs (best-effort — generated
    # palette never gives us these explicitly, so we mirror foreground/background).
    derived = {
        "primary-foreground":   palette.get("background", "0 0% 100%"),
        "secondary-foreground": palette.get("foreground", "0 0% 10%"),
        "accent-foreground":    palette.get("background", "0 0% 100%"),
        "muted-foreground":     palette.get("foreground", "0 0% 40%"),
        "card-foreground":      palette.get("foreground", "0 0% 10%"),
        "popover":              palette.get("card", "0 0% 100%"),
        "popover-foreground":   palette.get("foreground", "0 0% 10%"),
        "input":                palette.get("border", "0 0% 90%"),
        "ring":                 palette.get("primary", "220 90% 56%"),
        "destructive":          "0 84% 60%",
        "destructive-foreground": "0 0% 100%",
    }
    for k, v in derived.items():
        lines.append(f"    --{k}: {v};")
    return "\n".join(lines)


def write_landing_globals_css(workspace_path: str, brief: dict[str, Any]) -> str:
    palette = dict(brief.get("palette") or {})
    typo = dict(brief.get("typography") or {})
    css = _GLOBALS_TEMPLATE.format(
        palette_vars=_palette_vars(palette),
        heading_font=typo.get("heading_font", "Inter"),
        body_font=typo.get("body_font", "Inter"),
    )
    target = os.path.join(workspace_path, "src", "app", "globals.css")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8") as fh:
        fh.write(css)
    return target


