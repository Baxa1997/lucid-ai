# ── Reveal.jsx (scroll-triggered entrance) ───────────────────────────

_REVEAL_SRC = '''"use client";

import { useEffect, useRef, useState } from "react";

const VARIANTS = {
  "fade-up":    { hidden: "opacity-0 translate-y-6",  shown: "opacity-100 translate-y-0" },
  "fade-down":  { hidden: "opacity-0 -translate-y-6", shown: "opacity-100 translate-y-0" },
  "fade-left":  { hidden: "opacity-0 translate-x-6",  shown: "opacity-100 translate-x-0" },
  "fade-right": { hidden: "opacity-0 -translate-x-6", shown: "opacity-100 translate-x-0" },
  "fade":       { hidden: "opacity-0",                shown: "opacity-100" },
  "scale":      { hidden: "opacity-0 scale-95",       shown: "opacity-100 scale-100" },
};

/**
 * Scroll-triggered entrance wrapper. Drop into any section to reveal
 * its children when they enter the viewport. Stagger groups with the
 * `delay` prop (milliseconds).
 */
export default function Reveal({
  children,
  as: As = "div",
  variant = "fade-up",
  delay = 0,
  duration = 700,
  className = "",
  once = true,
}) {
  const ref = useRef(null);
  const [shown, setShown] = useState(false);
  const v = VARIANTS[variant] || VARIANTS["fade-up"];

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    if (typeof IntersectionObserver === "undefined") {
      setShown(true);
      return;
    }
    const io = new IntersectionObserver(
      (entries) => {
        entries.forEach((e) => {
          if (e.isIntersecting) {
            setShown(true);
            if (once) io.disconnect();
          } else if (!once) {
            setShown(false);
          }
        });
      },
      { threshold: 0.12, rootMargin: "0px 0px -40px 0px" }
    );
    io.observe(el);
    return () => io.disconnect();
  }, [once]);

  return (
    <As
      ref={ref}
      style={{ transitionDelay: `${delay}ms`, transitionDuration: `${duration}ms` }}
      className={`transition-all ease-out will-change-transform ${shown ? v.shown : v.hidden} ${className}`}
    >
      {children}
    </As>
  );
}
'''


def write_landing_reveal(workspace_path: str) -> str:
    target = os.path.join(workspace_path, "src", "components", "ui", "Reveal.jsx")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8") as fh:
        fh.write(_REVEAL_SRC)
    return target


