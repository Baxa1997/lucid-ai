_HEADER_STUBS_BY_ARCHETYPE = {
    "transparent-pill": _HEADER_SRC_PILL,
    "centered-logo":    _HEADER_SRC_CENTERED,
    "solid-bar":        _HEADER_SRC,
    # side-rail and mega-menu are too complex for stubs — fall back to the
    # solid-bar baseline if Claude codegen fails for those archetypes.
    "side-rail":        _HEADER_SRC,
    "mega-menu":        _HEADER_SRC,
}


def write_landing_header(workspace_path: str, brief: dict[str, Any] | None = None) -> str:
    """Write the Phase-0 stub header — picked from the Brief's archetype.

    Three distinct stubs ship by default (pill, centered, solid). Claude
    codegen still tries to overwrite this with a per-project version, but
    if codegen fails (rate limits, etc.), at least the stub matches the
    brief's chosen vibe instead of always defaulting to the white solid bar.
    """
    archetype = ""
    if brief:
        archetype = (brief.get("header_archetype") or "").strip().lower()
    src = _HEADER_STUBS_BY_ARCHETYPE.get(archetype, _HEADER_SRC)
    target = os.path.join(workspace_path, "src", "components", "layout", "MarketingHeader.jsx")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8") as fh:
        fh.write(src)
    logger.info("write_landing_header: stub=%s", archetype or "default-solid-bar")
    return target


